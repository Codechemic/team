-- 냉장고를 부탁해 · Supabase(PostgreSQL) 스키마
-- Supabase 대시보드 > SQL Editor 에서 01 → 02 → 03 → 04 → seed 순서로 실행
-- ERD와 다른 점: USER 테이블은 Supabase Auth(auth.users)가 로그인 정보를 맡고, profiles 가 닉네임 등을 저장
--               ADMIN 은 profiles 를 가리키는 관리자 목록, recipe 에 화면 표시용 emoji 추가

create table profiles (
  id          uuid primary key,                 -- auth.users.id 와 같은 값
  nickname    varchar(50)  not null unique,
  email       varchar(100),
  created_at  timestamptz  not null default now()
);

create table admin (
  admin_id  uuid primary key references profiles(id) on delete cascade
);

create table recipe (
  recipe_id       bigint generated by default as identity primary key,
  writer_id       uuid          not null references profiles(id) on delete cascade,
  title           varchar(200)  not null,
  intro           varchar(200),
  emoji           varchar(10),
  main_photo      varchar(255),
  cooking_time    int           not null check (cooking_time > 0),
  difficulty      varchar(20)   not null check (difficulty in ('쉬움','보통','어려움')),
  category        varchar(50),
  servings        int           not null default 2 check (servings > 0),
  views           int           not null default 0,
  saves           int           not null default 0,
  average_rating  numeric(3,2)  not null default 0,
  created_at      timestamptz   not null default now()
);

create table recipe_step (
  step_id        bigint generated by default as identity primary key,
  recipe_id      bigint  not null references recipe(recipe_id) on delete cascade,
  step_number    int     not null,
  description    text    not null,
  step_photo     varchar(255),
  timer_seconds  int,
  unique (recipe_id, step_number)
);

create table ingredient (
  ingredient_id    bigint generated by default as identity primary key,
  name             varchar(100) not null unique,
  category         varchar(50)  not null,           -- 채소/육류/수산물/기타/양념
  emoji            varchar(10),
  substitute_info  varchar(255),
  is_standard      boolean      not null default true,
  is_seasoning     boolean      not null default false  -- true 면 일치율 계산에서 제외
);

create table ingredient_alias (
  alias_id       bigint generated by default as identity primary key,
  alias_name     varchar(100) not null unique,      -- 예: 파
  ingredient_id  bigint       not null references ingredient(ingredient_id) on delete cascade  -- 예: 대파
);

create table recipe_ingredient (
  recipe_id      bigint        not null references recipe(recipe_id) on delete cascade,
  ingredient_id  bigint        not null references ingredient(ingredient_id),
  quantity       numeric(6,2),                      -- null = 약간
  unit           varchar(10)   not null,
  primary key (recipe_id, ingredient_id)
);
create index idx_ri_ingredient on recipe_ingredient(ingredient_id);

create table favorite (
  favorite_id  bigint generated by default as identity primary key,
  user_id      uuid    not null references profiles(id) on delete cascade,
  recipe_id    bigint  not null references recipe(recipe_id) on delete cascade,
  created_at   timestamptz not null default now(),
  unique (user_id, recipe_id)
);

create table review (
  review_id   bigint generated by default as identity primary key,
  recipe_id   bigint        not null references recipe(recipe_id) on delete cascade,
  writer_id   uuid          not null references profiles(id) on delete cascade,
  rating      numeric(2,1)  not null check (rating between 1 and 5),
  content     text,
  photo       varchar(255),
  created_at  timestamptz   not null default now()
);

create table comment (
  comment_id         bigint generated by default as identity primary key,
  parent_comment_id  bigint references comment(comment_id) on delete cascade,  -- null = 원댓글
  recipe_id          bigint not null references recipe(recipe_id) on delete cascade,
  writer_id          uuid   not null references profiles(id) on delete cascade,
  content            text   not null,
  reg_date           timestamptz not null default now()
);

create table follow (
  follow_id     bigint generated by default as identity primary key,
  follower_id   uuid not null references profiles(id) on delete cascade,
  following_id  uuid not null references profiles(id) on delete cascade,
  unique (follower_id, following_id),
  check (follower_id <> following_id)
);

create table fridge_item (
  fridge_item_id  bigint generated by default as identity primary key,
  user_id         uuid   not null references profiles(id) on delete cascade,
  ingredient_id   bigint not null references ingredient(ingredient_id),
  expiry_date     date,
  saved_at        timestamptz not null default now(),
  unique (user_id, ingredient_id)
);

create table recent_search (
  search_id      bigint generated by default as identity primary key,
  user_id        uuid   not null references profiles(id) on delete cascade,
  ingredient_id  bigint not null references ingredient(ingredient_id),  -- 검색어 글자 대신 표준 재료 ID
  searched_at    timestamptz not null default now()
);
create index idx_recent_user on recent_search(user_id, searched_at desc);

create table user_preference (
  user_id     uuid primary key references profiles(id) on delete cascade,
  diet_type   varchar(30),
  updated_at  timestamptz not null default now()
);

create table user_ingredient_preference (
  user_id          uuid   not null references profiles(id) on delete cascade,
  ingredient_id    bigint not null references ingredient(ingredient_id),
  preference_type  varchar(20) not null check (preference_type in ('선호','기피')),
  created_at       timestamptz not null default now(),
  primary key (user_id, ingredient_id)
);

create table notification (
  notification_id  bigint generated by default as identity primary key,
  user_id          uuid    not null references profiles(id) on delete cascade,
  type             varchar(30)  not null,
  related_type     varchar(30),
  related_id       bigint,
  message          varchar(255) not null,
  is_read          boolean not null default false,
  created_at       timestamptz not null default now()
);

create table report (
  report_id              bigint generated by default as identity primary key,
  reporter_id            uuid   not null references profiles(id) on delete cascade,
  target_type            varchar(20)  not null check (target_type in ('RECIPE','COMMENT')),
  target_id              bigint not null,
  reason                 varchar(200) not null,
  status                 varchar(20)  not null default '대기' check (status in ('대기','처리 완료','반려')),
  created_at             timestamptz  not null default now(),
  processed_by_admin_id  uuid references admin(admin_id),
  unique (reporter_id, target_type, target_id)     -- 같은 게시물 중복 신고 방지 (UC-F04)
);
